static void decodeFrames(const uint8_t* frame, size_t len,
                         int width, int height,
                         rfb::ModifiablePixelBuffer* pb)
{
  rfb::H264Decoder decoder;
  rfb::ServerParams server;
  core::Rect rect(0, 0, width, height);
  std::vector<uint8_t> buf(8 + len);

  server.setDimensions(width, height);
  server.setPF(pb->getPF());

  // Open H.264 rect: length, flags (bit 0 resets the decoder), data
  buf[0] = (len >> 24) & 0xff;
  buf[1] = (len >> 16) & 0xff;
  buf[2] = (len >> 8) & 0xff;
  buf[3] = len & 0xff;
  buf[4] = buf[5] = buf[6] = 0;
  buf[7] = 1;
  memcpy(&buf[8], frame, len);

  // A few times, as a decoder may hold a frame until the next one
  for (int i = 0; i < 3; i++) {
    decoder.decodeRect(rect, buf.data(), buf.size(), server, pb);
    buf[7] = 0;
  }
}

static void expectGrey(const rfb::PixelBuffer* pb, int x, int y)
{
  int stride;
  const uint8_t* pixel;
  uint8_t rgb[3];

  pixel = pb->getBuffer(core::Rect(x, y, x+1, y+1), &stride);
  pb->getPF().rgbFromBuffer(rgb, pixel, 1);

  // YUV round trips are not exact
  EXPECT_NEAR(rgb[0], 0x80, 8) << "at " << x << "," << y;
  EXPECT_NEAR(rgb[1], 0x80, 8) << "at " << x << "," << y;
  EXPECT_NEAR(rgb[2], 0x80, 8) << "at " << x << "," << y;
}

static void checkFrame(const uint8_t* frame, size_t len,
                       int width, int height)
{
  rfb::PixelFormat pf(32, 24, false, true, 255, 255, 255, 16, 8, 0);
  rfb::ManagedPixelBuffer pb(pf, width, height);
  uint32_t black = 0;

  pb.fillRect(pb.getRect(), &black);

  decodeFrames(frame, len, width, height, &pb);

  expectGrey(&pb, 0, 0);
  expectGrey(&pb, width/2, height/2);
  expectGrey(&pb, width-1, height-1);
}

class H264DecoderTest : public testing::Test {
protected:
  void SetUp() override
  {
#ifdef WIN32
    CoInitializeEx(nullptr, COINIT_MULTITHREADED);
#endif
  }
  void TearDown() override
  {
#ifdef WIN32
    CoUninitialize();
#endif
  }
};

TEST_F(H264DecoderTest, decode1080p)
{
  checkFrame(frame1080, sizeof(frame1080), 1920, 1080);
}

// Larger than the 1920x1088 the Windows decoder was initially sized for
TEST_F(H264DecoderTest, decode1440p)
{
  checkFrame(frame1440, sizeof(frame1440), 2560, 1440);
}
